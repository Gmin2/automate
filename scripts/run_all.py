"""run every test case and write results/<case>/matches.json plus results/README.md

python scripts/run_all.py [path/to/WM290V_RedrawStart.stp]
"""
import json
import sys
from argparse import Namespace
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from automate.cli import run  # noqa: E402

lathe = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "assignment" / "WM290V_RedrawStart.stp"
belt = "01. Test00-180 x 1 SPZ Type 1 1610 TL"
CASES = [
    ("lathe-chuck-key", lathe, "Key", "2,4,16,18", "chuck key square tip into the pinion sockets"),
    ("lathe-belt-big-pulley", lathe, belt, "27,23,31", "v-belt inner faces (big wrap) into the 180 pulley groove"),
    ("lathe-belt-small-pulley", lathe, belt, "29,25,33", "v-belt small wrap vs 80 pulley: flank angle 71 vs 73, near miss"),
    ("lathe-taper-bush-1610", lathe, "1610x38mm", "5", "taper bush outer cone into its pulley"),
    ("lathe-taper-bush-1210", lathe, "1210 TL Ø20 PILOT BORE", "3", "taper bush outer cone into its pulley"),
    ("lathe-pilot-bore", lathe, "1210 TL Ø20 PILOT BORE", "12", "20 mm pilot bore: the 24 mm motor shaft must not match"),
    ("bench-vice-jaw", ROOT / "data/external/bench_vice.stp", "Vice Jaw", "3,27,4,6", "real CATIA bench vice: jaw sliding on the base"),
]
for c in json.loads((ROOT / "fixtures/cases.json").read_text()):
    CASES.append((f"fixture-{Path(c['file']).stem}-{c['part']}", ROOT / "fixtures" / c["file"], c["part"],
                  ",".join(map(str, c["faces"])), c["note"]))

rows = []
for name, path, part, faces, note in CASES:
    if not Path(path).exists():
        print(f"skip {name}: {path} missing")
        continue
    out = ROOT / "results" / name
    out.mkdir(parents=True, exist_ok=True)
    args = Namespace(assembly=str(path), part=part, instance=None, part_step=None, faces=faces,
                     out=str(out / "matches.json"), quiet=True)
    res = run(args)
    ms = res["matches"]
    summary = "; ".join(f"{m['instance'].split('/')[-1]} {list(m['target_faces'].values())[0]} "
                        f"{m['fit']}/{m['motion']} gap {m['clearance']:.3f}" + (" (in place)" if m["in_place"] else "")
                        for m in ms) or "no match"
    here = res["in_place_contacts"]
    if not ms and here:
        summary += f" (touching now, partial: no contact on {here['no_contact']})"
    rows.append((name, part, faces, note, len(ms), summary, res["seconds"]))
    print(f"{name}: {len(ms)} match(es) {res['seconds']}s")

lines = ["# results", "", "generated by `python scripts/run_all.py`. each folder has the full `matches.json`.", "",
         "| case | selection | what it tests | matches | result | s |", "|---|---|---|---|---|---|"]
for name, part, faces, note, n, summary, secs in rows:
    lines.append(f"| {name} | {part} #{faces} | {note} | {n} | {summary} | {secs} |")
lines += ["", "## screenshots", "", "orange = selected faces, green = exact fit, blue = sliding fit, translucent copies = "
          "where the selected part would sit at each match.", ""]
for name, *_ in rows:
    if (ROOT / "results" / name / "screenshot.jpg").exists():
        lines += [f"### {name}", "", f"![{name}]({name}/screenshot.jpg)", ""]
(ROOT / "results" / "README.md").write_text("\n".join(lines) + "\n")
